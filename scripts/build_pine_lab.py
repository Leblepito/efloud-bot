#!/usr/bin/env python3
"""Assemble the Pine lab family from single-source parts (spec §2).

pine/lab/head_indicator.pine + core.pine + tail_indicator.pine → pine/efloud_lab.pine
pine/lab/head_strategy.pine  + core.pine + tail_strategy.pine  → pine/efloud_lab_strategy.pine

`--check` exits 1 when a committed generated file differs from the build output.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAB = ROOT / "pine" / "lab"
PARTS: dict[Path, list[str]] = {
    ROOT / "pine" / "efloud_lab.pine": ["head_indicator.pine", "core.pine", "tail_indicator.pine"],
    ROOT / "pine" / "efloud_lab_strategy.pine": ["head_strategy.pine", "core.pine", "tail_strategy.pine"],
}
BANNER = "// GENERATED by scripts/build_pine_lab.py — edit pine/lab/*, never this file.\n"


def build() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for target, parts in PARTS.items():
        chunks = [(LAB / p).read_text(encoding="utf-8").rstrip("\n") + "\n" for p in parts]
        first, _, head_rest = chunks[0].partition("\n")       # //@version=6 must stay line 1
        out[target] = first + "\n" + BANNER + head_rest + "".join("\n" + c for c in chunks[1:])
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify committed outputs, write nothing")
    args = ap.parse_args(argv)
    stale: list[Path] = []
    for path, content in build().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    for p in stale:
        print(f"STALE: {p.relative_to(ROOT)} — run: python scripts/build_pine_lab.py", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
